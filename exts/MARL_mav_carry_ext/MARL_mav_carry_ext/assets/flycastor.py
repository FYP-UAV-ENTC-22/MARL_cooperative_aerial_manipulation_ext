"""Configuration for the CASTOR rig: the flycrane's Falcons and rigid-rod cables with the CASTOR payload.

The URDF and the spawn joint angles are generated by ``scripts/tools/gen_castor_urdf.py`` from the
flycrane URDF and ``data/AMR/flycastor_data/castor_rig.yaml``. The URDF is converted to USD on first use
and cached in ``data/AMR/flycastor``; the converter redoes it whenever the URDF changes.
"""

from __future__ import annotations

from pathlib import Path

import yaml

import isaaclab.sim as sim_utils
from isaaclab.assets import ArticulationCfg

from .flycrane_rod import FLYCRANE_CFG

data_dir = Path(__file__).parent / "data/AMR"
urdf_path = data_dir / "flycrane_rod_data/flycastor.urdf"
spawn_joint_pos = yaml.safe_load((data_dir / "flycastor_data/castor_spawn.yaml").read_text())["joint_pos"]

##
# Configuration
##

FLYCASTOR_CFG = FLYCRANE_CFG.replace(
    spawn=sim_utils.UrdfFileCfg(
        asset_path=str(urdf_path.resolve()),
        usd_dir=str((data_dir / "flycastor").resolve()),
        # the settings the flycrane USD was converted with
        fix_base=False,
        merge_fixed_joints=False,
        self_collision=False,
        joint_drive=sim_utils.UrdfConverterCfg.JointDriveCfg(
            target_type="none",
            gains=sim_utils.UrdfConverterCfg.JointDriveCfg.PDGainsCfg(stiffness=0.0, damping=0.0),
        ),
        rigid_props=FLYCRANE_CFG.spawn.rigid_props,
        articulation_props=FLYCRANE_CFG.spawn.articulation_props,
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, 0.0),
        # Rods tilted outward and the drones levelled again; every other joint stays at zero.
        joint_pos=spawn_joint_pos,
        joint_vel={".*": 0.0},
    ),
)
"""Configuration for the CASTOR rig (3 x Falcon on rigid-rod cables, disc payload)."""
