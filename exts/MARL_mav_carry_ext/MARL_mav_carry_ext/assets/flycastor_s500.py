"""Configuration for the S500 rig: three S500 quadrotors carrying a disc on cables that can go slack.

The URDF and the spawn joint angles are generated by ``scripts/tools/gen_s500_rig_urdf.py`` from
``data/AMR/flycastor_s500_data/s500_rig.yaml``. The URDF is converted to USD on first use and cached in
``data/AMR/flycastor_s500``; the converter redoes it whenever the URDF changes.
"""

from __future__ import annotations

from pathlib import Path

import yaml

import isaaclab.sim as sim_utils
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets import ArticulationCfg

data_dir = Path(__file__).parent / "data/AMR"
urdf_path = data_dir / "flycastor_s500_data/flycastor_s500.urdf"
spawn_joint_pos = yaml.safe_load((data_dir / "flycastor_s500_data/s500_spawn.yaml").read_text())["joint_pos"]

##
# Configuration
##

FLYCASTOR_S500_CFG = ArticulationCfg(
    prim_path="{ENV_REGEX_NS}/Flycastor",
    spawn=sim_utils.UrdfFileCfg(
        asset_path=str(urdf_path.resolve()),
        usd_dir=str((data_dir / "flycastor_s500").resolve()),
        fix_base=False,
        merge_fixed_joints=False,
        self_collision=False,
        # Every joint is passive: the cable is a constraint, not a drive.
        joint_drive=sim_utils.UrdfConverterCfg.JointDriveCfg(
            target_type="none",
            gains=sim_utils.UrdfConverterCfg.JointDriveCfg.PDGainsCfg(stiffness=0.0, damping=0.0),
        ),
        rigid_props=sim_utils.RigidBodyPropertiesCfg(
            disable_gravity=False,
            max_depenetration_velocity=10.0,
            enable_gyroscopic_forces=True,
        ),
        articulation_props=sim_utils.ArticulationRootPropertiesCfg(
            enabled_self_collisions=False,
            solver_position_iteration_count=8,
            solver_velocity_iteration_count=1,
            sleep_threshold=0.0,  # a payload hanging still must not fall asleep
            stabilization_threshold=0.001,
        ),
    ),
    init_state=ArticulationCfg.InitialStateCfg(
        pos=(0.0, 0.0, 0.0),
        # Cables tilted outward at full length and the drones levelled again; every other joint stays at zero.
        joint_pos=spawn_joint_pos,
        joint_vel={".*": 0.0},
    ),
    actuators={
        "rotor_joints": ImplicitActuatorCfg(
            joint_names_expr=["Falcon.*_rotor_.*_joint"],
            stiffness=None,
            damping=None,
        ),
        "cable_joints": ImplicitActuatorCfg(
            joint_names_expr=["rope_.*"],
            stiffness=0.0,
            damping=0.0,
        ),
    },
)
"""Configuration for the S500 rig (3 x S500, disc payload, cables that can go slack)."""
