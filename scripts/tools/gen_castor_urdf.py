#!/usr/bin/env python3
"""Generate the CASTOR rig URDF from the flycrane's: same drones, same rigid-rod cables, new payload.

Reads ``flycrane_rod_data/flycrane.urdf`` (three Falcons, one rigid rod per cable, a ball joint at each
end) and changes only what ``flycastor_data/castor_rig.yaml`` lists:

* the payload becomes a disc of the given radius, height and mass, with its origin at its centre;
* the three cable anchors move to the disc's rim, 120 degrees apart, counter-clockwise seen from above;
* the rods take the given length.

Each anchor frame is yawed so its x axis points radially outward. That makes the spawn pose two joint
angles per cable: ``+spawn_angle`` on the anchor's y axis tilts the rod outward, ``-spawn_angle`` on the
drone-end y axis levels the drone again. They are written to ``castor_spawn.yaml``, which the asset
config reads. The result is written next to the flycrane URDF, where its meshes are.

Needs only PyYAML, not Isaac Sim::

    python scripts/tools/gen_castor_urdf.py
"""

from __future__ import annotations

import argparse
import math
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

DATA_DIR = Path(__file__).resolve().parents[2] / "exts/MARL_mav_carry_ext/MARL_mav_carry_ext/assets/data/AMR"
NUM_DRONES = 3


def fmt(values) -> str:
    return " ".join(f"{v:.6g}" for v in values)


def named(root: ET.Element, tag: str, name: str) -> ET.Element:
    for element in root.findall(tag):
        if element.get("name") == name:
            return element
    raise SystemExit(f"the template has no {tag} named {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--template", type=Path, default=DATA_DIR / "flycrane_rod_data/flycrane.urdf")
    parser.add_argument("--config", type=Path, default=DATA_DIR / "flycastor_data/castor_rig.yaml")
    parser.add_argument("--out", type=Path, default=DATA_DIR / "flycrane_rod_data/flycastor.urdf")
    args = parser.parse_args()

    cfg = yaml.safe_load(args.config.read_text())
    p, cable = cfg["payload"], cfg["cable"]
    tree = ET.parse(args.template)
    root = tree.getroot()
    root.set("name", "flycastor")

    # payload: a disc in place of the basket, with the odometry frame at its centre
    load = named(root, "link", "load_link")
    for child in list(load):
        load.remove(child)
    r, h, m = p["radius"], p["height"], p["mass"]
    for tag in ("visual", "collision"):
        shape = ET.SubElement(load, tag)
        ET.SubElement(shape, "origin", rpy="0 0 0", xyz="0 0 0")
        ET.SubElement(ET.SubElement(shape, "geometry"), "cylinder", radius=f"{r:.6g}", length=f"{h:.6g}")
    inertial = ET.SubElement(load, "inertial")
    ET.SubElement(inertial, "mass", value=f"{m:.6g}")
    ET.SubElement(inertial, "origin", rpy="0 0 0", xyz="0 0 0")
    transverse = m * (3 * r * r + h * h) / 12.0
    ET.SubElement(
        inertial, "inertia", ixx=f"{transverse:.6g}", ixy="0", ixz="0", iyy=f"{transverse:.6g}", iyz="0",
        izz=f"{0.5 * m * r * r:.6g}",
    )
    named(root, "joint", "load/odometry_sensor_joint").find("origin").set("xyz", "0 0 0")

    length, theta = cable["length"], math.radians(cable["spawn_angle_deg"])
    spawn = {}
    for i in range(1, NUM_DRONES + 1):
        # the rod itself
        rod = named(root, "link", f"rope_{i}_link")
        for tag in ("visual", "collision"):
            rod.find(tag).find("origin").set("xyz", fmt((0, 0, length / 2)))
            rod.find(tag).find("geometry").find("cylinder").set("length", f"{length:.6g}")
        # payload end: on the rim, facing outward
        phi = math.radians(p["angle_offset_deg"]) + 2 * math.pi * (i - 1) / NUM_DRONES
        anchor = named(root, "joint", f"rope_{i}_sphere_joint_0_joint_x").find("origin")
        anchor.set("xyz", fmt((p["anchor_radius"] * math.cos(phi), p["anchor_radius"] * math.sin(phi), p["anchor_height"])))
        anchor.set("rpy", fmt((0, 0, phi)))
        # drone end: at the top of the rod
        named(root, "joint", f"rope_{i}_sphere_joint_7_joint_x").find("origin").set("xyz", fmt((0, 0, length)))
        spawn[f"rope_{i}_sphere_joint_0_joint_y"] = round(theta, 6)
        spawn[f"rope_{i}_sphere_joint_7_joint_y"] = round(-theta, 6)

    tree.write(args.out, xml_declaration=True, encoding="utf-8")
    spawn_path = args.config.with_name("castor_spawn.yaml")
    spawn_path.write_text(
        "# Generated by scripts/tools/gen_castor_urdf.py: joint angles that put the rig in its spawn pose.\n"
        + yaml.safe_dump({"joint_pos": spawn}, sort_keys=True)
    )

    radius = p["anchor_radius"] + length * math.sin(theta)
    height = p["anchor_height"] + length * math.cos(theta)
    print(f"wrote {args.out}\nwrote {spawn_path}")
    print(f"  drones spawn {radius:.3f} m from the payload axis, {height:.3f} m above its centre")
    for i in range(1, NUM_DRONES + 1):
        print(f"  Falcon{i} (one-hot slot {i - 1}): anchor at {p['angle_offset_deg'] + 120.0 * (i - 1):6.1f} deg")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
